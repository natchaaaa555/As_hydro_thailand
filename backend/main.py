class HydroTwinHandler(BaseHTTPRequestHandler):
    def do_GET(self):
        parsed = urlparse(self.path)

        if parsed.path == "/":
            self.send_response(200)
            self.send_header("Content-type", "text/html; charset=utf-8")
            self.end_headers()
            with open(HTML_PATH, "rb") as f:
                self.wfile.write(f.read())

        elif parsed.path == "/api/v1/forecast":
            params = parse_qs(parsed.query)
            basin_id = int(params.get("basin_id", [1])[0])
            hour = int(params.get("hour", [0])[0])
            scenario = params.get("scenario", ["mining_spill"])[0]

            conn = sqlite3.connect(DB_PATH)
            basin = conn.execute(
                "SELECT region, basin_name, center_lat, center_lon, zoom_level, base_speed_kmh FROM basins WHERE basin_id = ?",
                (basin_id,)
            ).fetchone()
            rows = conn.execute(
                "SELECT node_id, station_name, subdistrict, lon, lat, distance_km, dilution_factor FROM river_nodes WHERE basin_id = ? ORDER BY distance_km ASC",
                (basin_id,)
            ).fetchall()
            conn.close()

            region, basin_name, c_lat, c_lon, zoom, base_speed = basin
            max_dist = rows[-1][5] if rows else 100.0

            if scenario == "mining_spill":
                c0 = 0.055
                speed_kmh = base_speed * 1.15
            elif scenario == "heavy_rain":
                c0 = 0.028
                speed_kmh = base_speed * 1.60
            else:
                c0 = 0.004
                speed_kmh = base_speed * 0.85

            plume_center_km = hour * speed_kmh
            spread_km = max(12.0, max_dist * 0.16) + (hour * 0.5)

            features = []
            for node_id, name, subdist, lon, lat, dist_km, dilution in rows:
                background_as = 0.0035
                plume_conc = c0 * dilution * math.exp(-((dist_km - plume_center_km) ** 2) / (2 * (spread_km ** 2)))
                conc = round(background_as + plume_conc, 4)

                if conc > 0.020:
                    risk = "CRITICAL"
                    risk_th = "เกินเกณฑ์วิกฤต"
                elif conc > 0.010:
                    risk = "WARNING"
                    risk_th = "เฝ้าระวังสูง"
                else:
                    risk = "NORMAL"
                    risk_th = "เกณฑ์ปกติ"

                eta_total_hours = round(dist_km / speed_kmh, 1)
                remaining_hours = round(eta_total_hours - hour, 1)
                if dist_km == 0:
                    eta_text = "จุดอ้างอิงต้นน้ำ (x = 0 km)"
                elif remaining_hours > 0:
                    eta_text = f"คาดการณ์ถึงใน {remaining_hours} ชม. (t = {eta_total_hours}h)"
                elif remaining_hours >= -4.0:
                    eta_text = "มวลสารกำลังเคลื่อนผ่านสถานี"
                else:
                    eta_text = f"เคลื่อนผ่านแล้ว {abs(remaining_hours)} ชม."

                features.append({
                    "type": "Feature",
                    "geometry": {"type": "Point", "coordinates": [lon, lat]},
                    "properties": {
                        "node_id": node_id,
                        "station_name": name,
                        "subdistrict": subdist,
                        "distance_km": dist_km,
                        "arsenic_mgl": conc,
                        "risk_level": risk,
                        "risk_th": risk_th,
                        "eta_text": eta_text
                    }
                })

            response_data = {
                "basin": {
                    "basin_id": basin_id,
                    "region": region,
                    "basin_name": basin_name,
                    "center": [c_lat, c_lon],
                    "zoom": zoom,
                    "flow_speed_kmh": round(speed_kmh, 2),
                    "total_length_km": max_dist
                },
                "features": features
            }

            self.send_response(200)
            self.send_header("Content-type", "application/json; charset=utf-8")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(json.dumps(response_data).encode("utf-8"))
        else:
            self.send_response(404)
            self.end_headers()

